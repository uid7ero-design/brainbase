import { expect, test } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
import { enabled, origin } from './accounts';
import { contextFor, createOffering, createSchedule, query } from './support';

test.skip(!enabled, 'Requires disposable Scheduling harness');
test('preview and combine a saved template without changing its source or bookings', async ({ browser }, info) => {
  const ctx = await contextFor(browser, 'manager');
  try {
    const evidence = process.env.COACH_SESSION_EVIDENCE_DIR;
    if (evidence) await mkdir(evidence, { recursive: true });
    const output = (name: string) => evidence ? path.join(evidence, info.project.name + '-' + name) : info.outputPath(name);
    const page = await ctx.newPage();
    await page.setViewportSize(info.project.use.viewport ?? { width: 1440, height: 900 });
    const schedule = await createSchedule(ctx.request, 'Template library ' + info.project.name);
    const offering = await createOffering(ctx.request, schedule.id, 'Rally skills ' + info.project.name, { durationMinutes: 45, capacity: 8, priceCents: 0 });
    const day = new Date(Date.now() + 10 * 86400000).toISOString().slice(0, 10);
    async function openNewPlan(time: string) {
      await page.goto(origin + '/coaching/calendar?week=' + day);
      await page.getByLabel('Class and location').selectOption(JSON.stringify([offering.id, null]));
      await page.getByLabel('Class date', { exact: true }).fill(day);
      await page.getByLabel('Local start time').fill(time);
      await page.getByRole('button', { name: 'Add class date' }).click();
      const card = page.locator('article').filter({ has: page.getByRole('link', { name: offering.name, exact: true }) }).filter({ hasText: time });
      const link = card.getByRole('link', { name: offering.name, exact: true });
      await expect(link).toBeVisible();
      const id = (await link.getAttribute('href'))!.split('/').pop()!;
      await link.click();
      await page.getByRole('link', { name: 'Training plan', exact: true }).click();
      return id;
    }
    const source = await openNewPlan('09:00');
    await page.getByLabel('Drill name').fill('Rally progression');
    await page.getByLabel('Coaching notes').fill('Recover to centre');
    await page.getByLabel('Ground layout').selectOption('court');
    const templateName = 'Rally library ' + info.project.name;
    await page.getByLabel('Save as a reusable template (optional)').fill(templateName);
    await page.getByRole('button', { name: 'Save plan', exact: true }).click();
    await expect(page.getByText('Saved plan · version 1')).toBeVisible();
    const readPlan = (id: string) => query<{version:number;drills:{name:string;notes:string}[]}>('SELECT version,drills FROM scheduling_coach_training_plans WHERE occurrence_id=$1', [id]);
    const original = await readPlan(source);
    const target = await openNewPlan('11:00');
    await page.getByLabel('Drill name').fill('Warmup to retain');
    await page.getByLabel('Saved templates').selectOption(templateName);
    const previewButton = page.getByRole('button', { name: 'Preview template' });
    await previewButton.click();
    const preview = page.getByRole('dialog', { name: templateName + ' template preview' });
    await expect(preview).toContainText('Recover to centre');
    await expect(preview).toContainText('your plan is unchanged');
    await expect(preview.getByRole('img', {name:'Tennis court diagram'})).toBeVisible();
    expect(await preview.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
    await page.screenshot({path:output('template-preview.png')});
    await page.keyboard.press('Tab');
    await expect(page.getByRole('button', {name:'Close template preview'})).toBeFocused();
    await page.keyboard.press('Escape');
    await expect(previewButton).toBeFocused();
    expect(await readPlan(target)).toEqual([]);
    await page.getByRole('button', {name:'Add drills to plan'}).click();
    await expect(page.getByLabel('Drill name')).toHaveValue('Rally progression');
    await page.getByLabel('Coaching notes').fill('Adjusted for this class');
    await expect(page.getByRole('button', {name:'1. Warmup to retain 10 min'})).toBeVisible();
    expect(await readPlan(target)).toEqual([]);
    await page.getByRole('button', {name:'Save plan',exact:true}).click();
    await expect(page.getByText('Saved plan · version 1')).toBeVisible();
    await page.reload();
    const saved = await readPlan(target);
    expect(saved[0].drills.map(d=>d.name)).toEqual(['Warmup to retain','Rally progression']);
    expect(saved[0].drills[1].notes).toBe('Adjusted for this class');
    expect(await readPlan(source)).toEqual(original);
    expect(await query('SELECT id FROM scheduling_reservations WHERE occurrence_id=$1 OR occurrence_id=$2',[source,target])).toEqual([]);
    await page.getByLabel('Saved templates').selectOption(templateName);
    await previewButton.click();
    await expect(preview).toContainText('Recover to centre');
    await expect(preview).not.toContainText('Adjusted for this class');
    await page.keyboard.press('Escape');
    expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  } finally { await ctx.close(); }
});

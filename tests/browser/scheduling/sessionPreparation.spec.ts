import { expect, test } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
import { enabled, origin } from './accounts';
import { contextFor, createOffering, createSchedule, query } from './support';

test.skip(!enabled, 'Requires disposable Scheduling harness');
test('prepare, reorder, save and print a whole session without extra database writes', async ({ browser }, info) => {
  const ctx = await contextFor(browser, 'manager');
  try {
    const evidence = process.env.COACH_SESSION_EVIDENCE_DIR;
    if (evidence) await mkdir(evidence, { recursive: true });
    const output = (name: string) => evidence ? path.join(evidence, info.project.name + '-' + name) : info.outputPath(name);
    const page = await ctx.newPage();
    await page.setViewportSize(info.project.use.viewport ?? { width: 1440, height: 900 });
    const schedule = await createSchedule(ctx.request, 'Session sheet ' + info.project.name);
    const offering = await createOffering(ctx.request, schedule.id, 'Court skills ' + info.project.name, { durationMinutes: 60, capacity: 8, priceCents: 0 });
    const day = new Date(Date.now() + 10 * 86400000).toISOString().slice(0, 10);
    await page.goto(origin + '/coaching/calendar?week=' + day);
    await page.getByLabel('Class and location').selectOption(JSON.stringify([offering.id, null]));
    await page.getByLabel('Class date', { exact: true }).fill(day);
    await page.getByLabel('Local start time').fill('09:00');
    await page.getByRole('button', { name: 'Add class date' }).click();
    const rosterLink = page.getByRole('link', { name: offering.name, exact: true });
    const rosterHref = await rosterLink.getAttribute('href');
    const id = rosterHref!.split('/').pop();
    await rosterLink.click();
    await page.getByLabel('Name', { exact: true }).fill('Synthetic sheet athlete');
    await page.getByLabel('Email', { exact: true }).fill('sheet@example.test');
    await page.getByRole('button', { name: 'Enrol participant' }).click();
    await expect(page.getByRole('heading', { name: 'Synthetic sheet athlete' })).toBeVisible();
    const bookings = () => query('SELECT * FROM scheduling_reservations WHERE occurrence_id=$1 ORDER BY id', [id]);
    const originalBookings = await bookings();
    expect(originalBookings).toHaveLength(1);
    const plans = () => query<{ version: number; drills: { name: string; notes: string; marks: unknown[] }[] }>('SELECT version,drills FROM scheduling_coach_training_plans WHERE occurrence_id=$1', [id]);
    await page.getByRole('link', { name: 'Training plan' }).click();
    await page.getByLabel('Drill name').fill('Rally warmup');
    await page.getByLabel('Minutes', { exact: true }).fill('15');
    await page.getByLabel('Coaching notes').fill('Aim deep\nRecover to centre');
    await page.getByLabel('Ground layout').selectOption('court');
    await page.getByLabel('Place on board').selectOption({ label: 'Synthetic sheet athlete' });
    await page.getByRole('button', { name: 'Column 3, row 4', exact: true }).click();
    await page.getByRole('button', { name: 'Duplicate drill' }).click();
    await expect(page.getByLabel('Drill name')).toHaveValue('Rally warmup (copy)');
    await expect(page.getByLabel('Coaching notes')).toHaveValue('Aim deep\nRecover to centre');
    await page.getByLabel('Drill name').fill('Volley progression');
    await page.getByLabel('Minutes', { exact: true }).fill('20');
    await page.getByRole('button', { name: 'Remove last marking' }).click();
    await page.getByRole('button', { name: 'Move earlier' }).click();
    await page.getByRole('button', { name: 'Move later' }).click();
    await page.getByRole('button', { name: '1. Rally warmup 15 min' }).click();
    await expect(page.getByRole('list', { name: 'Board players' })).toContainText('Synthetic sheet athlete');
    const opener = page.getByRole('button', { name: 'Session sheet', exact: true });
    await opener.click();
    const sheet = page.getByRole('dialog', { name: offering.name + ' session sheet' });
    await expect(sheet).toContainText('Unsaved draft');
    await expect(sheet).toContainText('0–15 min');
    await expect(sheet).toContainText('15–35 min');
    await expect(sheet).toContainText('25 min remaining');
    await expect(sheet).not.toContainText('Synthetic sheet athlete');
    await expect(sheet.getByRole('img', { name: 'Tennis court diagram' })).toHaveCount(2);
    await page.getByRole('button', { name: 'Print session sheet' }).focus();
    await page.keyboard.press('Tab');
    await expect(page.getByRole('button', { name: 'Close session sheet' })).toBeFocused();
    await page.keyboard.press('Escape');
    await expect(opener).toBeFocused();
    expect(await plans()).toEqual([]);
    await page.getByRole('button', { name: 'Save plan', exact: true }).click();
    await expect(page.getByText('Saved plan · version 1')).toBeVisible();
    await page.reload();
    const saved = await plans();
    expect(saved).toHaveLength(1);
    expect(saved[0].drills.map(d => d.name)).toEqual(['Rally warmup', 'Volley progression']);
    expect(saved[0].drills[0].marks).toHaveLength(1);
    expect(saved[0].drills[1].marks).toHaveLength(0);
    await opener.click();
    await expect(sheet).toContainText('Saved plan · version 1');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
    expect(await sheet.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
    await page.screenshot({ path: output('session-sheet-screen.png') });
    await sheet.getByRole('heading', { name: 'Volley progression' }).scrollIntoViewIfNeeded();
    await expect(sheet.getByRole('heading', { name: 'Volley progression' })).toBeInViewport();
    await page.screenshot({ path: output('session-sheet-second-drill.png') });
    // Exercise the real print stylesheet without opening a platform print dialog.
    await page.emulateMedia({ media: 'print' });
    expect(await page.locator('html').evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgb(255, 255, 255)');
    await expect(page.getByRole('button', { name: 'Print session sheet' })).not.toBeVisible();
    await expect(page.getByRole('navigation', { name: 'Primary' })).not.toBeVisible();
    await expect(sheet.getByRole('img')).toHaveCount(2);
    await page.pdf({ path: output('session-sheet.pdf'), format: 'A4', printBackground: true, margin: { top: '12mm', right: '12mm', bottom: '12mm', left: '12mm' } });
    await page.emulateMedia({ media: 'screen' });
    await page.keyboard.press('Escape');
    expect(await plans()).toEqual(saved);
    expect(await bookings()).toEqual(originalBookings);
  } finally {
    await ctx.close();
  }
});

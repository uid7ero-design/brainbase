import assert from 'node:assert/strict';
export async function verifyOrganisationUsers({origin,context,page,q,emails,browser,contextOptions}) {
  const endpoint=origin+'/api/organisation/users';
  const foreign=(await q("INSERT INTO users(id,organisation_id,username,name,role,updated_at) VALUES('org-user-foreign','local-other','org-user-foreign','Foreign admin','ADMIN',now()) RETURNING id")).rows[0];
  const listingResponse=await context.request.get(endpoint);assert.equal(listingResponse.status(),200,await listingResponse.text());
  const listing=await listingResponse.json();
  assert.ok(!listing.users.some(u=>u.id===foreign.id));
  const invalid={action:'invite',name:'Invited employee',email:'org-user@example.test',role:'super_admin',permissions:{people:'view'}};
  assert.equal((await context.request.post(endpoint,{data:invalid})).status(),400);
  assert.equal((await context.request.post(endpoint,{data:{...invalid,role:'viewer',organisationId:'local-other'}})).status(),400);
  await page.goto(origin+'/settings/users');
  await page.getByRole('button',{name:'Invite user',exact:true}).click();
  await page.getByLabel('Name',{exact:true}).fill('Invited employee');
  await page.getByLabel('Email / username',{exact:true}).fill('org-user@example.test');
  await page.getByLabel('Access to People',{exact:true}).selectOption('view');
  const saved=page.waitForResponse(r=>r.url()===endpoint&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Create and send invitation',exact:true}).click();
  const savedResponse=await saved;assert.equal(savedResponse.status(),200,await savedResponse.text());
  const invited=await savedResponse.json();
  const mail=emails.find(e=>e.to==='org-user@example.test');assert.ok(mail,'Fixture sender must receive the invitation');
  const token=mail.html.match(/accept-invitation#token=([a-f0-9]{64})/)?.[1];assert.ok(token);
  const tokenRow=(await q('SELECT token_hash FROM organisation_user_invitations WHERE user_id=$1',[invited.id])).rows[0];assert.notEqual(tokenRow.token_hash,token);
  const guest=await browser.newContext(contextOptions);const guestPage=await guest.newPage();
  const newPassword='Local-invitation-strong-password';
  await guestPage.goto(origin+'/accept-invitation#token='+token);
  await guestPage.getByLabel('New password',{exact:true}).fill(newPassword);
  await guestPage.getByRole('button',{name:'Accept invitation',exact:true}).click();
  await guestPage.getByText('Your account is ready.',{exact:true}).waitFor();
  assert.equal((await guest.request.post(origin+'/api/auth/accept-invitation',{data:{token,password:newPassword}})).status(),400);
  await guestPage.goto(origin+'/login');await guestPage.getByLabel('Username',{exact:true}).fill('org-user@example.test');await guestPage.getByLabel('Password',{exact:true}).fill(newPassword);
  await guestPage.getByRole('button',{name:'Sign in',exact:true}).click();await guestPage.waitForURL('**/workspace');
  assert.equal((await guest.request.get(origin+'/api/hr/people')).status(),200);
  const denied=await guest.request.post(origin+'/api/hr/teams',{data:{name:'Denied write'}});assert.equal(denied.status(),403);assert.match((await denied.json()).error,/access to this area/);
  assert.equal((await guest.request.get(endpoint)).status(),403);
  assert.equal((await guest.request.get(origin+'/api/admin/users')).status(),403);
  assert.equal((await guest.request.get(origin+'/api/hr/people/foreign-person')).status(),404);
  const update={action:'update',id:invited.id,name:'Invited employee',role:'viewer',status:'ACTIVE',permissions:{people:'none'}};
  assert.equal((await context.request.post(endpoint,{data:{...update,id:foreign.id}})).status(),409);
  await page.getByRole('button',{name:'Edit access for Invited employee',exact:true}).click();
  await page.getByLabel('Access to People',{exact:true}).selectOption('none');
  let updateWrites=0;
  await page.route('**/api/organisation/users',async route=>{
    if(route.request().method()!=='POST')return route.continue();
    const actual=await route.fetch();assert.equal(actual.status(),200);updateWrites++;await route.abort('failed');
  });
  await page.getByRole('button',{name:'Save access',exact:true}).click();
  await page.getByText('The save result is unknown. Refresh users and check the saved account before trying again.',{exact:true}).waitFor();
  assert.equal(await page.getByRole('button',{name:'Save access',exact:true}).isDisabled(),true);
  await page.unroute('**/api/organisation/users');await page.getByRole('button',{name:'Refresh users',exact:true}).click();
  await page.getByRole('button',{name:'Edit access for Invited employee',exact:true}).waitFor();assert.equal(updateWrites,1);
  assert.equal((await q('SELECT permissions->>\'people\' AS access FROM organisation_user_access WHERE user_id=$1',[invited.id])).rows[0].access,'none');
  assert.equal((await guest.request.get(origin+'/api/hr/people')).status(),403);
  assert.equal((await context.request.post(endpoint,{data:{...update,status:'INACTIVE'}})).status(),200);
  assert.equal((await guest.request.get(origin+'/api/hr/people')).status(),401);
  await guest.close();
  emails.splice(emails.indexOf(mail),1); // The following HR reminder suite owns its own sender counts.
  assert.equal((await context.request.post(endpoint,{data:{...update,id:'local-admin',role:'viewer'}})).status(),400);
  await page.goto(origin+'/people');
  console.log('PASS: organisation user invitation UI, hashed single-use acceptance, real login, read-only enforcement, tenant/platform denial, permission revocation and inactive-session denial. Email uses the isolated local fixture.');
}

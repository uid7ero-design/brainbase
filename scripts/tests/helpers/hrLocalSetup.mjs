import assert from 'node:assert/strict';
import { expect as browserExpect } from '@playwright/test';
const expect = browserExpect.configure({ timeout: 30000 });

// Extends the real Next/login proof, sharing only its owned synthetic services.
export async function verifyHrSetup({ page, origin, person, q }) {
  async function lost(url, method, action) {
    let writes = 0;
    await page.route(url, async route => {
      if (route.request().method() !== method) return route.continue();
      const response = await route.fetch();
      assert.ok(response.ok(), `${method} returned ${response.status()}: ${await response.text()}`);
      writes++;
      await route.abort('failed');
    });
    await action();
    await expect.poll(() => writes).toBe(1);
    return async () => { assert.equal(writes, 1); await page.unroute(url); };
  }
  const dialog = name => page.getByRole('dialog', { name, exact: true });
  await page.goto(`${origin}/people/teams`);
  await page.getByRole('button', { name: '+ Create Team', exact: true }).click();
  await dialog('Create Team').getByLabel(/^Name/).fill('Setup Team');
  await dialog('Create Team').getByRole('button', { name: 'Create Team', exact: true }).click();
  await expect(dialog('Create Team')).toHaveCount(0);
  const team = (await q("SELECT id FROM hr_teams WHERE name='Setup Team'")).rows[0];
  assert.ok(team);
  await page.getByRole('button', { name: 'Edit Setup Team', exact: true }).click();
  await dialog('Edit Team').getByLabel(/^Name/).fill('Setup Team Revised');
  await dialog('Edit Team').getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(dialog('Edit Team')).toHaveCount(0);
  await page.getByRole('button', { name: 'Archive Setup Team Revised', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm archive Setup Team Revised', exact: true }).click();
  await expect(page.getByText('Setup Team Revised', { exact: true })).toHaveCount(0);
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Restore Setup Team Revised', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Edit Setup Team Revised', exact: true })).toBeVisible();

  await page.goto(`${origin}/people`);
  await page.getByRole('button', { name: '+ Add Person', exact: true }).click();
  const add = dialog('Add Person');
  await add.getByLabel(/^First Name/).fill('Setup');
  await add.getByLabel(/^Last Name/).fill('Person');
  await add.getByLabel('Team', { exact: true }).selectOption(team.id);
  await add.getByLabel('Manager', { exact: true }).selectOption(person.id);
  await add.getByLabel('Linked BrainBase Account', { exact: true }).selectOption('local-admin');
  await expect(add.locator('select option[value="local-employee"]')).toBeDisabled();
  await add.getByLabel('Start Date', { exact: true }).fill('2026-10-17');
  const finishCreate = await lost(`${origin}/api/hr/people`, 'POST', () => add.getByRole('button', { name: 'Create Person', exact: true }).click());
  await expect(add.getByText(/The save could not be confirmed/)).toBeVisible();
  await expect(add.getByRole('button', { name: 'Create Person', exact: true })).toBeDisabled();
  await finishCreate();
  const createdRows = (await q("SELECT id, linked_user_id, manager_person_id, team_id FROM hr_people WHERE first_name='Setup' AND last_name='Person'")).rows;
  assert.equal(createdRows.length, 1);
  assert.equal(createdRows[0].linked_user_id, 'local-admin');
  assert.equal(createdRows[0].manager_person_id, person.id);
  assert.equal(createdRows[0].team_id, team.id);
  await add.getByRole('button', { name: 'Close Add Person', exact: true }).click();
  await page.getByRole('button', { name: 'Setup Person', exact: true }).click();
  await dialog('Person').getByRole('button', { name: 'Edit', exact: true }).click();
  const edit = dialog('Edit Person');
  await edit.getByLabel('Job Title', { exact: true }).fill('Local setup role');
  await expect(edit.getByRole('button', { name: 'Save changes', exact: true })).toBeEnabled();
  const finishEdit = await lost(`${origin}/api/hr/people/${createdRows[0].id}`, 'PATCH', () => edit.getByRole('button', { name: 'Save changes', exact: true }).click());
  await expect(edit.getByText(/The save could not be confirmed/)).toBeVisible();
  await expect(edit.getByRole('button', { name: 'Save changes', exact: true })).toBeDisabled();
  await finishEdit();
  assert.equal((await q('SELECT job_title FROM hr_people WHERE id=$1', [createdRows[0].id])).rows[0].job_title, 'Local setup role');
  await edit.getByRole('button', { name: 'Close Edit Person', exact: true }).click();

  await page.goto(`${origin}/people/administrators`);
  await page.getByRole('combobox', { name: 'User to grant HR administrator access', exact: true }).selectOption('local-manager');
  const finishGrant = await lost(`${origin}/api/hr/administrators`, 'POST', () => page.getByRole('button', { name: 'Grant', exact: true }).click());
  await expect(page.getByText(/Could not confirm/)).toBeVisible();
  await finishGrant();
  await page.getByRole('button', { name: 'Refresh', exact: true }).click();
  await page.getByRole('button', { name: 'Revoke HR administrator access for local-manager', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm revoke HR administrator access for local-manager', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Revoke HR administrator access for local-manager', exact: true })).toHaveCount(0);
  await expect.poll(async () => (await q("SELECT count(*)::int AS n FROM hr_administrators WHERE user_id='local-manager'")).rows[0].n).toBe(0);
  console.log('PASS: actual setup forms: team lifecycle, explicit person/team/manager/account linking, lost person create/edit and administrator grant recovery without repeated writes.');

  const templatesUrl = `${origin}/api/hr/lifecycle/templates`;
  await page.goto(`${origin}/people/lifecycle-templates`);
  await page.getByRole('button', { name: '+ Create Template', exact: true }).click();
  const create = dialog('Create lifecycle template');
  await create.getByLabel(/^Template key/).fill('setup-browser');
  await create.getByLabel(/^Name/).fill('Setup template');
  await create.getByLabel(/^Task title/).fill('Setup task');
  const finishTemplate = await lost(templatesUrl, 'POST', () => create.getByRole('button', { name: 'Create template', exact: true }).click());
  await expect(create.getByRole('button', { name: 'Create template', exact: true })).toBeDisabled();
  await expect(create.getByText(/The change could not be confirmed/)).toBeVisible();
  await create.getByRole('button', { name: 'Close Create lifecycle template', exact: true }).click();
  await expect(create).toBeVisible();
  await finishTemplate();
  await create.getByRole('button', { name: 'Check saved templates', exact: true }).click();
  await expect(create).toHaveCount(0);
  const original = (await q("SELECT id FROM hr_lifecycle_templates WHERE template_key='setup-browser'")).rows;
  assert.equal(original.length, 1);
  const templateId = original[0].id;
  async function statusAction(name, id, action) {
    await page.getByRole('button', { name: `View ${name}`, exact: true }).click();
    const panel = dialog(name);
    await panel.getByRole('button', { name: action === 'activate' ? 'Activate' : 'Retire', exact: true }).click();
    const confirm = action === 'activate' ? 'Confirm activate' : 'Confirm retire';
    const finish = await lost(`${templatesUrl}/${id}/${action}`, 'POST', () => panel.getByRole('button', { name: confirm, exact: true }).click());
    await expect(panel.getByRole('button', { name: confirm, exact: true })).toBeDisabled();
    await expect(panel.getByText(/The change could not be confirmed/)).toBeVisible();
    await expect(panel.getByRole('button', { name: 'Keep template', exact: true })).toBeDisabled();
    await finish();
    await panel.getByRole('button', { name: 'Check saved templates', exact: true }).click();
    await expect(panel).toHaveCount(0);
  }
  await statusAction('Setup template', templateId, 'activate');
  await page.getByRole('button', { name: 'View Setup template', exact: true }).click();
  await dialog('Setup template').getByRole('button', { name: 'Create new version', exact: true }).click();
  const version = dialog('Create lifecycle template version');
  await version.getByLabel(/^Name/).fill('Setup template revision');
  const finishVersion = await lost(`${templatesUrl}/${templateId}/versions`, 'POST', () => version.getByRole('button', { name: 'Create version', exact: true }).click());
  await expect(version.getByRole('button', { name: 'Create version', exact: true })).toBeDisabled();
  await expect(version.getByText(/The change could not be confirmed/)).toBeVisible();
  await finishVersion();
  await version.getByRole('button', { name: 'Check saved templates', exact: true }).click();
  await expect(version).toHaveCount(0);
  const revisions = (await q("SELECT id, version_number FROM hr_lifecycle_templates WHERE template_key='setup-browser' ORDER BY version_number")).rows;
  assert.equal(revisions.length, 2);
  assert.equal(revisions[1].version_number, 2);
  await statusAction('Setup template revision', revisions[1].id, 'retire');
  assert.deepEqual((await q("SELECT status FROM hr_lifecycle_templates WHERE template_key='setup-browser' ORDER BY version_number")).rows.map(r => r.status), ['ACTIVE', 'RETIRED']);
  await page.route(templatesUrl, route => route.fulfill({ status: 503, json: { error: 'Private synthetic failure detail' } }));
  await page.getByRole('button', { name: 'Refresh', exact: true }).click();
  await expect(page.getByText('Could not load lifecycle templates.', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: '+ Create Template', exact: true })).toHaveCount(0);
  await expect(page.getByText('Private synthetic failure detail')).toHaveCount(0);
  await page.unroute(templatesUrl);
  await page.getByRole('button', { name: 'Refresh', exact: true }).click();
  await expect(page.getByRole('button', { name: '+ Create Template', exact: true })).toBeVisible();
  console.log('PASS: actual template forms: create/version/activate/retire lost-response locks, saved-state reconciliation, immutable version history and failed-read permission clearing/recovery.');
}
